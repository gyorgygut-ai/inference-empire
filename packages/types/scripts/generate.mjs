// Generates packages/types/src/generated.ts from packages/contracts/src/*.json.
// No external deps: maps the JSON-schema subset used by contracts to TS.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { join, basename, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const contractsDir = join(__dirname, "../../contracts/src")
const outFile = join(__dirname, "../src/generated.ts")

const nested = []

function tsType(schema, hint) {
  const types = Array.isArray(schema.type) ? schema.type : [schema.type ?? "unknown"]
  const nonNull = types.filter((t) => t !== "null")
  const nullable = nonNull.length < types.length
  const base = nonNull.map((t) => {
    if (t === "string") return "string"
    if (t === "integer" || t === "number") return "number"
    if (t === "boolean") return "boolean"
    if (t === "array") {
      const items = schema.items ? tsType(schema.items, hint) : "unknown"
      return `${items}[]`
    }
    if (t === "object") {
      if (schema.properties) {
        nested.push(interfaceBlock(hint, schema))
        return hint
      }
      return "Record<string, unknown>"
    }
    return "unknown"
  })
  const union = [...new Set(base)].join(" | ")
  return nullable ? `${union} | null` : union
}

function interfaceBlock(name, schema) {
  const required = new Set(schema.required ?? [])
  const lines = [`export interface ${name} {`]
  for (const [key, prop] of Object.entries(schema.properties ?? {})) {
    const opt = required.has(key) ? "" : "?"
    lines.push(`  ${key}${opt}: ${tsType(prop, `${name}${toPascal(key)}`)}`)
  }
  lines.push("}")
  return lines.join("\n")
}

function toPascal(s) {
  return s
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("")
}

const files = readdirSync(contractsDir).filter((f) => f.endsWith(".json")).sort()
const chunks = ["// AUTO-GENERATED by packages/types/scripts/generate.mjs — do not edit."]
const registry = []

for (const file of files) {
  const stem = basename(file, ".json")
  const contract = JSON.parse(readFileSync(join(contractsDir, file), "utf8"))
  const pascal = toPascal(stem)
  const inName = `${pascal}Input`
  const outName = `${pascal}Output`
  if (contract.input) chunks.push("", interfaceBlock(inName, contract.input))
  if (contract.output) chunks.push("", interfaceBlock(outName, contract.output))
  if (nested.length) {
    chunks.push("", ...nested)
    nested.length = 0
  }
  registry.push(`  ${JSON.stringify(stem)}: { input: ${inName}; output: ${outName} }`)
}

chunks.push("", "export interface ContractMap {", ...registry, "}", "")
chunks.push("export type ContractName = keyof ContractMap", "")

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, chunks.join("\n"))
console.log(`generated ${outFile} from ${files.length} contracts`)
